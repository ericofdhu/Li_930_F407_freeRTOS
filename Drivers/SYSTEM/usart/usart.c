HAL_StatusTypeDef usart3_send_string_dma(const char *str)
{
    size_t length;

    if (str == NULL)
    {
        return HAL_ERROR;
    }

    length = strlen(str);
    if (length == 0U)
    {
        return HAL_OK;
    }
    if (length > 0xFFFFU)
    {
        return HAL_ERROR;
    }

    return HAL_UART_Transmit_DMA(&huart3, (const uint8_t *)str,
                                 (uint16_t)length);
}



